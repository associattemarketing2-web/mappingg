// Builds components/icons/fa-subset.css (bundled into the page CSS by IconFont.tsx): Font Awesome 6.4.0 with only the icon rules
// the site actually uses. The full stylesheet has ~2,450 icon rules (100 KB);
// applying it after hydration forced a full style recalculation and layout of the
// page. Base rules (.fa/.fas/.fab, @font-face, animations, sizing) are kept whole.
//
//   node scripts/build-icon-css.mjs      (also runs automatically before `npm run build`)
//
// Icons are found by scanning the source for "fa-…" class tokens, so a newly used
// icon is picked up on the next build. Fonts still load from the cdnjs copy of
// Font Awesome Free 6.4.0 (Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT).

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const SRC = path.join(ROOT, 'vendor/fontawesome/all-6.4.0.min.css');
const OUT = path.join(ROOT, 'components/icons/fa-subset.css'); // imported by components/IconFont.tsx
const WEBFONTS = 'https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/webfonts/';
const SCAN = [
  ['app', /\.(tsx?|css)$/], ['components', /\.(tsx?|css)$/], ['lib', /\.tsx?$/],
  ['public', /^[^/\\]+\.js$/], ['public/legacy', /\.json$/], ['public/partners', /\.(js|html)$/],
];

function walk(dir, re, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (!['node_modules', '.next'].includes(e.name) && !dir.endsWith('public')) walk(p, re, out); }
    else if (re.test(e.name) && p !== OUT) out.push(p); // never scan our own output
  }
  return out;
}

const used = new Set();
for (const [d, re] of SCAN) {
  for (const f of walk(path.join(ROOT, d), re)) {
    for (const m of fs.readFileSync(f, 'utf8').matchAll(/\bfa-[a-z0-9]+(?:-[a-z0-9]+)*/g)) used.add(m[0]);
  }
}

// Split the minified CSS into top-level blocks (rules and at-rules).
const css = fs.readFileSync(SRC, 'utf8');
const header = css.match(/^\/\*![\s\S]*?\*\//)?.[0] || '';
const body = css.slice(header.length);
const blocks = [];
let depth = 0, start = 0;
for (let i = 0; i < body.length; i++) {
  if (body[i] === '{') depth++;
  else if (body[i] === '}' && --depth === 0) { blocks.push(body.slice(start, i + 1).trim()); start = i + 1; }
}

const ICON_SEL = /^\.(fa-[a-z0-9-]+)::?before$/;
let kept = 0, dropped = 0;
const out = [];
for (const b of blocks) {
  const brace = b.indexOf('{');
  const selector = b.slice(0, brace);
  if (selector.startsWith('@')) { out.push(b); continue; } // @font-face, @keyframes, @media…
  const parts = selector.split(',');
  if (!parts.every((s) => ICON_SEL.test(s.trim()))) { out.push(b); continue; } // base / utility rule
  const keep = parts.filter((s) => used.has(s.trim().match(ICON_SEL)[1]));
  if (keep.length) { out.push(keep.join(',') + b.slice(brace)); kept += keep.length; } else dropped += parts.length;
}

const result = `${header}\n/* Subset generated by scripts/build-icon-css.mjs — do not edit by hand. */\n${out.join('')}`
  .replace(/url\(\.\.\/webfonts\//g, `url(${WEBFONTS}`);
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, result);
console.log(`fa-subset.css: ${kept} icon selectors kept, ${dropped} dropped, ${(result.length / 1024).toFixed(1)} KB (was ${(css.length / 1024).toFixed(1)} KB); ${used.size} fa-* tokens found in the source`);
