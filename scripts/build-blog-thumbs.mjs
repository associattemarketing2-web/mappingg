// node scripts/build-blog-thumbs.mjs
//
// Small WebP copies (640 px wide) of the blog cover images in public/img/blog,
// for the places that show covers as cards (home page "Insights", /blog list).
// The 1200×630 JPEG originals are ~100 KB each and were downloaded at full size
// for ~300 px wide cards. Writes public/img/blog/thumbs/<name>-640.webp and
// lib/blog-thumbs.ts (the list lib/blog-thumb.ts checks, so a cover without a
// thumbnail simply keeps its original). Idempotent: existing thumbs are skipped.
// Run it after adding new cover images (sharp is already a dependency).

import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const DIR = 'public/img/blog';
const OUT = path.join(DIR, 'thumbs');
const W = 640;
fs.mkdirSync(OUT, { recursive: true });
const names = [];
let made = 0, before = 0, after = 0;
for (const f of fs.readdirSync(DIR)) {
  if (!/\.(jpe?g|png)$/i.test(f)) continue;
  const base = f.replace(/\.(jpe?g|png)$/i, '');
  const out = path.join(OUT, `${base}-${W}.webp`);
  if (!fs.existsSync(out)) {
    await sharp(path.join(DIR, f)).resize({ width: W, withoutEnlargement: true }).webp({ quality: 72, effort: 6 }).toFile(out);
    made++;
  }
  before += fs.statSync(path.join(DIR, f)).size;
  after += fs.statSync(out).size;
  names.push(f);
}
fs.writeFileSync(
  'lib/blog-thumbs.ts',
  '// Generated by scripts/build-blog-thumbs.mjs: blog covers that have a 640px WebP thumbnail.\n'
    + `export const BLOG_THUMBS: readonly string[] = ${JSON.stringify(names.sort(), null, 1)};\n`,
);
console.log(`[blog-thumbs] ${names.length} covers, ${made} new thumbs; originals ${(before / 1048576).toFixed(1)} MB → thumbs ${(after / 1048576).toFixed(1)} MB`);
