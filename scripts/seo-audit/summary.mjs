// Writes SEO-AUDIT-SUMMARY.md for the latest run (or --out=<dir>), with a
// before/after table when --compare=<baseline run folder> is given.
// Numbers come only from the crawl and DB reports in those folders.

import path from 'node:path';
import { existsSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { arg, latestDir, readJson, writeCsv } from './common.mjs';

const dir = arg('out') ? path.resolve(String(arg('out'))) : await latestDir();
if (!dir) throw new Error('No audit run found — run npm run seo:audit first');
const crawl = await readJson(path.join(dir, 'seo-audit-results.json'));
const proj = existsSync(path.join(dir, 'projects-summary.json')) ? await readJson(path.join(dir, 'projects-summary.json')) : null;
const cmpDir = arg('compare') ? path.resolve(String(arg('compare'))) : null;
const before = cmpDir ? await readJson(path.join(cmpDir, 'seo-audit-results.json')) : null;

const s = crawl.summary;
const sev = (x, k) => (x.issues_by_severity || {})[k] || 0;
const code = (x, k) => (x.issues_by_code || {})[k] || 0;
const row = (label, a, b) => `| ${label} | ${before ? `${a} | ` : ''}${b} |`;
const metrics = [
  ['URLs crawled', (x) => x.fetched],
  ['Indexable pages (200, no noindex, self-canonical)', (x) => x.indexable_200],
  ['Sitemap URLs', (x) => x.sitemap?.urls],
  ['HTTP 404 / 5xx', (x) => `${x.status_counts?.['404'] || 0} / ${Object.entries(x.status_counts || {}).filter(([k]) => k >= 500).reduce((n, [, v]) => n + v, 0)}`],
  ['Duplicate title groups', (x) => x.duplicate_title_groups],
  ['Duplicate description groups', (x) => x.duplicate_description_groups],
  ['Missing title / description / canonical', (x) => `${x.missing_title} / ${x.missing_description} / ${x.missing_canonical}`],
  ['Pages with schema errors', (x) => x.schema_error_pages],
  ['Broken internal links', (x) => code(x, 'broken-internal-link')],
  ['Titles over ~70 chars', (x) => code(x, 'title-long')],
  ['Descriptions over 170 chars', (x) => code(x, 'description-long')],
  ['Thin pages (<150 words, indexable)', (x) => code(x, 'thin-content')],
  ['Orphan pages', (x) => code(x, 'orphan')],
  ['Titles with ALL-CAPS names', (x) => code(x, 'title-all-caps')],
  ['Issues: high / medium / low', (x) => `${sev(x, 'critical') + sev(x, 'high')} / ${sev(x, 'medium')} / ${sev(x, 'low')}`],
];

const lines = [];
lines.push(`# SEO audit summary — ${path.basename(dir)}`, '');
lines.push(`Crawled \`${s.base}\` from ${s.started} to ${s.finished}. Generated by \`npm run seo:audit\` (scripts/seo-audit).`, '');
lines.push(`- Routes in source (static pages in \`app/\`): ${s.source_static_routes}; URLs discovered: ${s.discovered}; fetched: ${s.fetched}${s.limit_hit ? ' (**crawl limit reached — not every URL was checked**)' : ' (all discovered URLs checked)'}.`);
lines.push(`- Page types: ${Object.entries(s.page_types).map(([k, v]) => `${k} ${v}`).join(', ')}.`);
lines.push(`- Sitemap: ${s.sitemap.urls} URLs, well-formed: ${s.sitemap.wellFormed ? 'yes' : 'NO'}, duplicates: ${s.sitemap.duplicates}, off-origin: ${s.sitemap.offOrigin}.`);
lines.push(`- robots.txt: HTTP ${s.robots.status}; disallows ${s.robots.disallow.join(', ')}; sitemap ${s.robots.sitemaps.join(', ')}.`, '');
lines.push(`## ${before ? `Before (${path.basename(cmpDir)}) vs after` : 'Key numbers'}`, '');
lines.push(before ? '| Metric | Before | After |' : '| Metric | Value |', before ? '| --- | --- | --- |' : '| --- | --- |');
for (const [label, f] of metrics) lines.push(row(label, before ? f(before.summary) : '', f(s)));
lines.push('');
if (proj) {
  lines.push('## Projects and blog (database, read-only)', '');
  lines.push(`- Public pins: ${proj.public_pins}; property projects: ${proj.property_projects}; not projects (office/land markers, no page): ${proj.not_projects}.`);
  lines.push(`- Indexable project pages: ${proj.indexable_projects}; noindex placeholders (no details yet): ${proj.noindex_placeholders}.`);
  lines.push(`- By city: ${Object.entries(proj.by_city).map(([k, v]) => `${k} ${v}`).join(', ')}.`);
  lines.push(`- Data gaps (projects missing the field): ${Object.entries(proj.missing).map(([k, v]) => `${k} ${v}`).join(', ')}.`);
  lines.push(`- Projects with a RERA number: ${proj.with_rera}; ALL-CAPS names (title-cased for display): ${proj.all_caps_names}; same name + locality as another pin: ${proj.duplicate_name_locality}; generic names: ${proj.generic_names}.`);
  lines.push(`- Generated project titles unique: ${proj.unique_titles} of ${proj.property_projects}; descriptions unique: ${proj.unique_descriptions}.`);
  lines.push(`- Blog posts: ${proj.blog_posts} (published ${proj.published_posts}). Keyword rows mapped: ${proj.keyword_rows}.`, '');
}
lines.push('## Top issues', '');
const top = crawl.issues.filter((i) => ['critical', 'high'].includes(i.severity)).slice(0, 40);
if (!top.length) lines.push('No critical or high issues in this run.');
for (const i of top) lines.push(`- **${i.severity}** \`${i.code}\` ${i.url} — ${i.detail}`);
lines.push('', '## Files in this folder', '');
lines.push('- `PAGE-BY-PAGE-SEO.csv` — one row per URL (status, indexability, canonical, title, description, H1, words, links, schema, issues)');
lines.push('- `TECHNICAL-SEO-ISSUES.csv` — every issue with severity, evidence and fix');
lines.push('- `BLOG-SEO-REPORT.csv` (rendered pages) and `BLOG-CONTENT-REPORT.csv` (stored articles)');
lines.push('- `PROJECT-SEO-REPORT.csv` — one row per public pin: verified fields, generated title/description, keywords, data gaps');
lines.push('- `KEYWORD-URL-MAPPING.csv` — one target query per indexable URL, intent, cannibalisation risk');
lines.push('- `seo-audit-results.json`, `projects-summary.json` — machine-readable results', '');
lines.push('Search Console data is not included: the Search Console API is not enabled for the site’s Google Cloud project, so no clicks, impressions, rankings or index status are reported. "Indexable" means technically indexable, not indexed by Google.');

await writeFile(path.join(dir, 'SEO-AUDIT-SUMMARY.md'), lines.join('\n') + '\n', 'utf8');

// Every baseline issue with its status in this run: fixed (no longer found) or open.
if (before) {
  const key = (i) => `${i.code} ${i.url}`;
  const now = new Map(crawl.issues.map((i) => [key(i), i]));
  const was = new Set(before.issues.map(key));
  const rows = [
    ...before.issues.map((i) => ({ ...i, status: now.has(key(i)) ? 'open' : 'fixed', after_detail: now.get(key(i))?.detail || '' })),
    ...crawl.issues.filter((i) => !was.has(key(i))).map((i) => ({ ...i, status: 'open (new in this run)', after_detail: i.detail, detail: '' })),
  ];
  await writeCsv(path.join(dir, 'ISSUES-BEFORE-AFTER.csv'), rows, ['severity', 'code', 'url', 'status', 'detail', 'after_detail', 'fix']);
  const fixed = rows.filter((r) => r.status === 'fixed').length;
  console.log(`[seo-summary] ISSUES-BEFORE-AFTER.csv: ${fixed} fixed, ${rows.length - fixed} open`);
}
console.log(`[seo-summary] ${path.relative(process.cwd(), path.join(dir, 'SEO-AUDIT-SUMMARY.md'))}`);
